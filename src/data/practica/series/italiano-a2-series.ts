import type { A1ListeningEpisode, A1ListeningSeries, EpisodeAudit } from './schema'

/**
 * Serie narrativa de escucha — Italiano A2.
 *
 * El esquema editorial se comparte con las series A1 (mismo runner, mismo adaptador);
 * lo único que cambia es el nivel declarado por la serie y la banda de unidades léxicas
 * que exige el validador (65–110 para A2 en alfabeto latino).
 *
 * `audit.level` sigue siendo 'A1' porque es el literal que comprueba
 * scripts/validate-listening-series.mjs para todas las series; el nivel real de la
 * colección lo declara `level: 'A2'` en la serie.
 */

const q = (prompt: string, options: string[], answer: number, feedback: string) => {
  const slot = [...prompt].reduce((sum, char) => sum + char.codePointAt(0)!, 0) % 3
  const rotated = options.filter((_, index) => index !== answer)
  rotated.splice(slot, 0, options[answer])
  return { prompt, options: rotated, answer: slot, feedback }
}

type EpisodeDraft = Omit<A1ListeningEpisode, 'ttsScript' | 'audit'> & {
  audit: Omit<EpisodeAudit, 'level' | 'estimatedDuration'>
}

const ep = (draft: EpisodeDraft): A1ListeningEpisode => ({
  ...draft,
  ttsScript: draft.turns.map((turn) => turn.target).join(' '),
  audit: { level: 'A2', estimatedDuration: draft.duration, ...draft.audit },
})


