import type { A1ListeningEpisode, A1ListeningSeries, EpisodeAudit } from './schema'

/**
 * Inglés A2 · temporada 2 de «The Corner Shop».
 *
 * El fichero anterior, ingles-a2-listening.ts, publicaba 20 episodios con `transcript: []`,
 * una sola pregunta de detalle y una «consolidación» que preguntaba qué estructura gramatical
 * organiza el episodio y daba como respuesta correcta el nombre de la estructura. Es decir:
 * sin texto que escuchar y con una pregunta que se acierta leyendo el título. Esta temporada
 * lo sustituye entero.
 *
 * Se conserva el arco narrativo y la progresión gramatical de aquellos episodios —past simple,
 * past continuous, comparativos, going to, will, present perfect, some/any, cuantificadores,
 * modales, primer condicional, gerundios, adverbios de modo y estilo indirecto—, que es la que
 * enseña /practica/ingles/a2/gramatica.
 */

const q = (prompt: string, options: string[], answer: number, feedback: string) => {
  const slot = [...prompt].reduce((sum, char) => sum + char.codePointAt(0)!, 0) % 3
  const rotated = options.filter((_, index) => index !== answer)
  rotated.splice(slot, 0, options[answer])
  return { prompt, options: rotated, answer: slot, feedback }
}

type EpisodeDraft = Omit<A1ListeningEpisode, 'ttsScript' | 'audit'> & {
  audit: Omit<EpisodeAudit, 'level' | 'estimatedDuration'>
}

const ep = (draft: EpisodeDraft): A1ListeningEpisode => ({
  ...draft,
  ttsScript: draft.turns.map((turn) => turn.target).join(' '),
  audit: { level: 'A2', estimatedDuration: draft.duration, ...draft.audit },
})

