/**
 * Alemán A2 · temporada 2 de «Emma in Berlin».
 *
 * Reescribe en diálogo los 20 monólogos de aleman-a2-listening.ts. Se conserva intacta la
 * progresión gramatical del original —Perfekt, Präteritum, dativo, comparativo, subordinadas,
 * relativo— porque es la misma que enseña /practica/aleman/a2/gramatica y cambiarla dejaría
 * las dos páginas contándose cosas distintas. Lo que cambia es la forma: dos o tres voces
 * alternando en vez de una narrando.
 *
 * La temporada termina donde empieza B1: Emma consigue el trabajo en el café de Herr Becker.
 */

const q = (prompt: string, options: string[], answer: number, feedback: string) => {
  const slot = [...prompt].reduce((sum, char) => sum + char.codePointAt(0)!, 0) % 3
  const rotated = options.filter((_, index) => index !== answer)
  rotated.splice(slot, 0, options[answer])
  return { prompt, options: rotated, answer: slot, feedback }
}

type EpisodeDraft = Omit<A1ListeningEpisode, 'ttsScript' | 'audit'> & {
  audit: Omit<EpisodeAudit, 'level' | 'estimatedDuration'>
}

const ep = (draft: EpisodeDraft): A1ListeningEpisode => ({
  ...draft,
  ttsScript: draft.turns.map((turn) => turn.target).join(' '),
  audit: { level: 'A2', estimatedDuration: draft.duration, ...draft.audit },
})

