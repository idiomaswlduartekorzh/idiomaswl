/**
 * Inglés B1 · temporada 3 de «The Corner Shop».
 *
 * Reescribe ingles-b1-listening.ts, que sí tenía transcripción pero arrastraba dos defectos:
 * un narrador que contaba la mitad de la trama —el nivel pide sostener conversación, no
 * escuchar a alguien narrando—, y una «consolidación» que preguntaba qué estructura organiza
 * el episodio y daba como respuesta el nombre de la estructura. Se acertaba leyendo el título.
 *
 * Se conserva el arco y la progresión: past continuous, past perfect, futuros, present
 * perfect y perfect continuous, condicionales, modales, pasiva, relativas, gerundios,
 * estilo indirecto, comparativos, cuantificadores, artículos, phrasal verbs, oraciones
 * temporales, question tags, wish y conectores.
 */

const q = (prompt: string, options: string[], answer: number, feedback: string) => {
  const slot = [...prompt].reduce((sum, char) => sum + char.codePointAt(0)!, 0) % 3
  const rotated = options.filter((_, index) => index !== answer)
  rotated.splice(slot, 0, options[answer])
  return { prompt, options: rotated, answer: slot, feedback }
}

type EpisodeDraft = Omit<A1ListeningEpisode, 'ttsScript' | 'audit'> & {
  audit: Omit<EpisodeAudit, 'level' | 'estimatedDuration'>
}

