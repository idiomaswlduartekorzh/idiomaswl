/**
 * Italiano A1 · temporada 1 de «La bicicletta gialla».
 *
 * Reescribe en diálogo los 20 monólogos de italiano-a1-ascolto.ts, con la misma progresión
 * gramatical —essere, avere, artículos, c'è/ci sono, reflexivos, negación, interrogativos,
 * posesivos, preposiciones articuladas, modales, stare + gerundio, sapere/potere, imperativo
 * y adverbios de frecuencia—, que es la que enseña /practica/italiano/a1/gramatica.
 *
 * Ocurre antes de A2: son las primeras semanas de Valeria en Bolonia, cuando todavía va a
 * todas partes a pie. La temporada termina el domingo en que descubre el mercadillo donde
 * comprará la bicicleta amarilla.
 */

const q = (prompt: string, options: string[], answer: number, feedback: string) => {
  const slot = [...prompt].reduce((sum, char) => sum + char.codePointAt(0)!, 0) % 3
  const rotated = options.filter((_, index) => index !== answer)
  rotated.splice(slot, 0, options[answer])
  return { prompt, options: rotated, answer: slot, feedback }
}

