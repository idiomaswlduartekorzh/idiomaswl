import type {
  EvidenceValue,
  MedicalResidencyBlueprint,
  OfficialExamDomain,
  OfficialSourceId,
} from './types.ts';

function explicit<T>(
  value: T,
  sourceIds: readonly OfficialSourceId[],
  note: string,
): EvidenceValue<T> {
  return { value, status: 'explicit', sourceIds, note };
}

function calculated<T>(
  value: T,
  sourceIds: readonly OfficialSourceId[],
  note: string,
): EvidenceValue<T> {
  return { value, status: 'calculated-from-official-schedule', sourceIds, note };
}

function notPublished<T>(
  sourceIds: readonly OfficialSourceId[],
  note: string,
): EvidenceValue<T> {
  return { value: null, status: 'not-published', sourceIds, note };
}

function domain(
  id: string,
  label: string,
  scope: OfficialExamDomain['scope'],
  sourceIds: readonly OfficialSourceId[],
): OfficialExamDomain {
  return { id, label, scope, sourceIds };
}

